"""Exercise actual glass/reflection plane histories and camera-cut invalidation.
Requires XML fixtures generated by test_stable_mirror_guides.py and OCIO.
"""
import csv
import json
from pathlib import Path
import subprocess
import time
from PIL import Image
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'test_outputs/stable_plane_history'
OUT.mkdir(parents=True, exist_ok=True)
startup = subprocess.STARTUPINFO()
startup.dwFlags |= subprocess.STARTF_USESHOWWINDOW
startup.wShowWindow = subprocess.SW_HIDE
report = []
for kind in ('mirror', 'mirror_chain', 'glass'):
    for window in (0,4):
        scene = ROOT / f'test_outputs/stable_mirror/{kind}.xml'
        assert scene.exists(), scene
        tag = f'{kind}_window{window}'
        command = [str(ROOT / 'install/photara_viewer.exe'), '--size', '256', '--spp', '1',
                   '--denoiser', 'DLSS', '--stable-plane-history', '4',
                   '--smoke-frames', '90', '--camera-sweep', '--camera-cut-frame', '40',
                   '--metrics', str(OUT / f'{tag}.csv'), '--screenshot', str(OUT / f'{tag}.bmp'),
                   str(scene)]
        if window == 0:
            pos = command.index('--stable-plane-history')
            del command[pos:pos+2]
        started = time.perf_counter()
        with (OUT / f'{tag}.log').open('w') as log:
            subprocess.run(command, stdout=log, stderr=log, check=True, timeout=600, startupinfo=startup)
        rows = list(csv.DictReader((OUT / f'{tag}.csv').open()))
        assert len(rows) == 90
        assert all(int(r['cpu_pixel_readback_bytes']) == 0 for r in rows)
        assert all(int(r['stable_planes']) == 1 for r in rows)
        assert all(int(r['dlss_resets']) == (i+1 if window else 1+int(i>=40))
                   for i,r in enumerate(rows))
        if not window:
            assert int(rows[-1]['dlss_reuses']) == 88
        assert all(0 <= float(r['plane_mean_history']) <= 4 for r in rows)
        assert int(rows[0]['plane_reused_pixels']) == 0
        assert int(rows[40]['plane_reused_pixels']) == 0
        if window:
            assert max(int(r['active_planes']) for r in rows) > 0
            assert max(int(r['plane_reused_pixels']) for r in rows[1:40]) > 0
            if kind == 'glass': assert max(int(r['active_planes']) for r in rows) > 256*256
        pixels = np.asarray(Image.open(OUT / f'{tag}.bmp'), dtype=np.float32)
        assert np.isfinite(pixels).all() and pixels[..., :3].std() > 10
        report.append(dict(kind=kind, window=window, seconds=time.perf_counter()-started,
                           active_planes=max(int(r['active_planes']) for r in rows),
                           reused_pixels=max(int(r['plane_reused_pixels']) for r in rows)))
(OUT / 'summary.json').write_text(json.dumps(report, indent=2))
print(json.dumps(report, indent=2))
